// Copies prisma/migrations/*/migration.sql into src/server/migrations.generated.ts, so the app can
// apply them itself when it starts, wherever the host puts the built files. Runs before every build.
import fs from 'node:fs'
import path from 'node:path'
const dir = 'prisma/migrations'
const list = fs.readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && fs.existsSync(path.join(dir, d.name, 'migration.sql')))
  .map((d) => ({ name: d.name, sql: fs.readFileSync(path.join(dir, d.name, 'migration.sql'), 'utf8') }))
  .sort((a, b) => a.name.localeCompare(b.name))
fs.writeFileSync(
  'src/server/migrations.generated.ts',
  `// Generated by scripts/embed-migrations.mjs from prisma/migrations. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(list, null, 0)}\n`,
)
console.log(`Embedded ${list.length} migration(s)`)
